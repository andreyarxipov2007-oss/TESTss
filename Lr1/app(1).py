# Ввод двоичной последовательности
S = input("Введите двоичную последовательность: ")

# Инициализация
decimal = 0
i = 0

# Проверка, что строка не пустая
if len(S) == 0:
    print("Ошибка: пустая строка")
else:
    # Основной цикл
    while i < len(S):
        bit = S[i]

        # Проверка корректности символа
        if bit != '0' and bit != '1':
            print("Ошибка: последовательность должна содержать только 0 и 1")
            break

        # Перевод
        decimal = decimal * 2
        decimal = decimal + int(bit)

        i += 1
    else:
        # Выполнится если не было break
        print("Десятичное значение:", decimal)
