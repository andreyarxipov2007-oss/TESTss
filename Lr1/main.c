#include <stdio.h>
#include <string.h>
int main() {
    // Объявление строки с фиксированным размером
    char str[100];
    int max_a = 0; // Максимальная длина последовательности 'a'
    int cur_a = 0; // Текущая длина последовательности 'a'
    int i;           // Счетчик для прохода по строке
    //  Ввод строки
    printf("Введите строку: ");
    fgets(str, sizeof(str), stdin);
    // Удаление символа новой строки '\n', который fgets добавляет в буфер
    str[strcspn(str, "\n")] = '\0';
    // Основной цикл - проход по каждому символу строки
    for (i = 0; i < strlen(str); i++) {
        if (str[i] == 'a') {
            // Текущий символ - 'a'
            cur_a++; // Увеличиваем длину текущей последовательности
        } else {
            //  Текущий символ НЕ 'a'
            // Проверяем, является ли только что завершенная последовательность самой длинной
            if (cur_a > max_a) {
                max_a = cur_a; // Обновляем максимум
            }
            cur_a = 0; // Сбрасываем счетчик текущей последовательности
        }
    }
    // Проверка после завершения цикла
    // Последовательность 'a' может заканчиваться строкой)
    if (cur_a > max_a) {
        max_a = cur_a;
    }
    //  Вывод результата
    printf("Длина самой длинной последовательности из 'a': %d\n", max_a);

    return 0;
}